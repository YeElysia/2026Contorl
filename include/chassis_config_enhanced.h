/*
Q1: 为什么标定后直线还是偏？
A1: 可能原因：
    1. 地面摩擦力不均匀（换场地测试）
    2. 轮子动态特性差异（高速和低速标定系数不同）
    3. IMU 漂移（长时间运行后检查）
    4. 电池电压下降影响电机特性

Q2: 航向保持修正会不会影响精度？
A2: 不会。航向修正通过同向旋转分量实现，不改变平移合成向量。
    但过强的修正可能在斜移时引起轮子打滑，这时需要降低参数。

Q3: 什么时候需要启用积分项？
A3: 仅当满足以下条件时：
    1. 距离标定已完成
    2. 存在持续的单向偏移（例如总是向左偏 2°）
    3. 机械调整无法消除
    4. 比例控制已调到合理上限
    谨慎使用，错误的积分参数会导致振荡！

Q4: 增强策略和简单 P 控制有什么区别？
A4: 增强策略包括：
    1. 区分直线和斜移，直线时允许更大修正
    2. 自适应增益（小误差高增益，大误差降增益）
    3. 速度相关的修正比例调整
    4. 可选的积分补偿
    但代码复杂度增加，建议先尝试调整基础参数。

Q5: 标定系数在不同速度下是否一致？
A5: 理论上应该一致，但实际可能有偏差：
    1. 麦轮在高速时打滑更严重
    2. 低速时静摩擦影响更明显
    如果差异 > 5%，建议分别标定快速档和精确档。
*/
